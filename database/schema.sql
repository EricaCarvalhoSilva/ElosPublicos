-- =====================================================================
-- ElosPúblicos — script de criação das tabelas (PostgreSQL 14+)
--
-- Espelha as classes de src/core/models.py, uma tabela por classe concreta.
-- As classes abstratas (Usuario e Publicacao) não viram tabela: seus
-- atributos são herdados pelas tabelas das subclasses
-- (cidadao/organizacao e postagem_apoio/publicacao_organizacao).
--
-- No dia a dia, quem cria as tabelas é o Django (python manage.py migrate).
-- Este script serve como documentação do banco e para criar o esquema
-- direto no PostgreSQL. Para gerar a versão exata a partir das migrations:
--     python manage.py sqlmigrate core 0001 > ../database/schema_gerado.sql
-- =====================================================================

BEGIN;

-- Classe Cidadao (herda de Usuario) — entidade principal
CREATE TABLE cidadao (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo            VARCHAR(150)  NOT NULL,
    email                    VARCHAR(254)  NOT NULL DEFAULT '',
    telefone                 VARCHAR(20)   NOT NULL,
    municipio                VARCHAR(100)  NOT NULL,
    uf                       VARCHAR(2)    NOT NULL,
    criado_em                TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    atualizado_em            TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    cpf                      VARCHAR(11)   NOT NULL UNIQUE,
    endereco                 VARCHAR(255)  NOT NULL,
    renda_familiar_declarada NUMERIC(10,2) NOT NULL CHECK (renda_familiar_declarada >= 0)
);

-- Classe Organizacao (herda de Usuario)
CREATE TABLE organizacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome_completo VARCHAR(150) NOT NULL,
    email         VARCHAR(254) NOT NULL DEFAULT '',
    telefone      VARCHAR(20)  NOT NULL,
    municipio     VARCHAR(100) NOT NULL,
    uf            VARCHAR(2)   NOT NULL,
    criado_em     TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    atualizado_em TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    cnpj          VARCHAR(14)  NULL UNIQUE,
    tipo          VARCHAR(20)  NOT NULL CHECK (tipo IN ('ONG', 'COLETIVO', 'ASSOCIACAO')),
    descricao     TEXT         NOT NULL DEFAULT ''
);

-- Composição 1:N — NucleoFamiliar ◆── MembroFamiliar
CREATE TABLE nucleo_familiar (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    responsavel_id BIGINT NOT NULL UNIQUE REFERENCES cidadao (id) ON DELETE CASCADE
);

CREATE TABLE membro_familiar (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nucleo_id       BIGINT       NOT NULL REFERENCES nucleo_familiar (id) ON DELETE CASCADE,
    nome_completo   VARCHAR(150) NOT NULL,
    parentesco      VARCHAR(10)  NOT NULL
                    CHECK (parentesco IN ('CONJUGE', 'FILHO', 'PAI_MAE', 'IRMAO', 'NETO', 'OUTRO')),
    data_nascimento DATE         NULL
);
CREATE INDEX membro_familiar_nucleo_idx ON membro_familiar (nucleo_id);

-- Classe ProgramaSocial
CREATE TABLE programa_social (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                    VARCHAR(150)  NOT NULL,
    esfera                  VARCHAR(10)   NOT NULL CHECK (esfera IN ('FEDERAL', 'ESTADUAL', 'MUNICIPAL')),
    uf                      VARCHAR(2)    NOT NULL DEFAULT '',
    municipio               VARCHAR(100)  NOT NULL DEFAULT '',
    orgao_responsavel       VARCHAR(150)  NOT NULL,
    descricao               TEXT          NOT NULL,
    criterios_elegibilidade TEXT          NOT NULL,
    documentacao_necessaria TEXT          NOT NULL,
    renda_per_capita_maxima NUMERIC(10,2) NULL,
    link_oficial            VARCHAR(200)  NOT NULL DEFAULT '',
    ativo                   BOOLEAN       NOT NULL DEFAULT TRUE
);
CREATE INDEX programa_social_regiao_idx ON programa_social (esfera, uf, municipio);

-- Classe Solicitacao (Cidadao 1:N Solicitacao N:1 ProgramaSocial)
CREATE TABLE solicitacao (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cidadao_id       BIGINT      NOT NULL REFERENCES cidadao (id) ON DELETE CASCADE,
    programa_id      BIGINT      NOT NULL REFERENCES programa_social (id) ON DELETE RESTRICT,
    orgao            VARCHAR(10) NOT NULL CHECK (orgao IN ('CRAS', 'CREAS', 'CADUNICO', 'INSS', 'OUTRO')),
    numero_protocolo VARCHAR(50) NOT NULL DEFAULT '',
    status           VARCHAR(20) NOT NULL DEFAULT 'REGISTRADA'
                     CHECK (status IN ('REGISTRADA', 'EM_ANALISE', 'PENDENTE_DOCUMENTOS', 'DEFERIDA', 'INDEFERIDA')),
    observacao       TEXT        NOT NULL DEFAULT '',
    data_registro    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    atualizado_em    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX solicitacao_cidadao_idx ON solicitacao (cidadao_id);
CREATE INDEX solicitacao_programa_idx ON solicitacao (programa_id);

-- Classe RedeApoio (N:N com Cidadao)
CREATE TABLE rede_apoio (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome      VARCHAR(120) NOT NULL,
    descricao TEXT         NOT NULL DEFAULT '',
    municipio VARCHAR(100) NOT NULL,
    uf        VARCHAR(2)   NOT NULL,
    criada_em TIMESTAMPTZ  NOT NULL DEFAULT NOW()
);

CREATE TABLE rede_apoio_membros (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    redeapoio_id BIGINT NOT NULL REFERENCES rede_apoio (id) ON DELETE CASCADE,
    cidadao_id   BIGINT NOT NULL REFERENCES cidadao (id) ON DELETE CASCADE,
    UNIQUE (redeapoio_id, cidadao_id)
);

-- Classe PostagemApoio (herda de Publicacao)
CREATE TABLE postagem_apoio (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo    VARCHAR(150) NOT NULL,
    descricao TEXT         NOT NULL,
    ativa     BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    rede_id   BIGINT       NOT NULL REFERENCES rede_apoio (id) ON DELETE CASCADE,
    autor_id  BIGINT       NOT NULL REFERENCES cidadao (id) ON DELETE CASCADE,
    natureza  VARCHAR(10)  NOT NULL CHECK (natureza IN ('OFERTA', 'PEDIDO')),
    tipo      VARCHAR(20)  NOT NULL CHECK (tipo IN ('DOACAO', 'TROCA_SERVICO', 'CARONA'))
);
CREATE INDEX postagem_apoio_rede_idx ON postagem_apoio (rede_id);

-- Classe PublicacaoOrganizacao (herda de Publicacao)
CREATE TABLE publicacao_organizacao (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo         VARCHAR(150) NOT NULL,
    descricao      TEXT         NOT NULL,
    ativa          BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em      TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    organizacao_id BIGINT       NOT NULL REFERENCES organizacao (id) ON DELETE CASCADE,
    tipo           VARCHAR(10)  NOT NULL CHECK (tipo IN ('EDITAL', 'OFICINA', 'EVENTO')),
    data_evento    TIMESTAMPTZ  NULL,
    local          VARCHAR(200) NOT NULL DEFAULT '',
    link_inscricao VARCHAR(200) NOT NULL DEFAULT ''
);

-- Classe IndicadorOrcamentario
CREATE TABLE indicador_orcamentario (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    municipio       VARCHAR(100)  NOT NULL,
    uf              VARCHAR(2)    NOT NULL,
    acao            VARCHAR(150)  NOT NULL,
    ano             INTEGER       NOT NULL CHECK (ano >= 0),
    valor_previsto  NUMERIC(14,2) NOT NULL CHECK (valor_previsto >= 0),
    valor_executado NUMERIC(14,2) NOT NULL CHECK (valor_executado >= 0),
    fonte           VARCHAR(200)  NOT NULL DEFAULT '',
    CONSTRAINT indicador_unico_por_ano UNIQUE (municipio, uf, acao, ano)
);

COMMIT;
